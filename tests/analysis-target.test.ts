describe("what counts as an analysis target", () => {
  it("keeps product code of every stack in the target", () => {
    for (const path of IN_TARGET) expect(analysisNoiseKind(path), path).toBeNull();
    for (const path of IN_TARGET) expect(isAnalysisTarget(path), path).toBe(true);
  });

  it("keeps tests, docs, migrations, build, deployment, generated, type and vendored files out, and says why", () => {
    for (const [path, kind] of NOISE) expect(analysisNoiseKind(path), path).toBe(kind);
    for (const [path] of NOISE) expect(isAnalysisTarget(path), path).toBe(false);
  });

  it("is case-insensitive throughout", () => {
    expect(analysisNoiseKind("Src/Test/java/Foo.java")).toBe("test");
    expect(analysisNoiseKind("README.MD")).toBe("doc");
    expect(analysisNoiseKind("DockerFile")).toBe("deployment");
    expect(analysisNoiseKind("Third_Party/x.c")).toBe("vendored");
  });

  it("does not treat a code file as a document because of its name alone", () => {
    // 旧规则把任何叫 security / support / authors / notice 的文件都当文档，lib/security.ts 这样的产品代码因此被漏掉。
    for (const path of ["lib/security.ts", "src/support.ts", "app/api/authors.ts", "lib/notice.ts", "governance.go", "History.ts"]) {
      expect(analysisNoiseKind(path), path).toBeNull();
    }
  });

  it("knows the manifests the planner needs to recognise a stack, and nothing else", () => {
    for (const path of ["package.json", "go.mod", "Cargo.toml", "pyproject.toml", "pom.xml", "build.gradle.kts", "AndroidManifest.xml", "App.csproj", "App.sln", "composer.json", "requirements.txt"]) {
      expect(isBuildManifest(path), path).toBe(true);
      expect(isAnalysisTarget(path), path).toBe(true);
    }
    for (const path of ["Makefile", "CMakeLists.txt", "package-lock.json", "Dockerfile", "requirements.lock"]) expect(isBuildManifest(path), path).toBe(false);
  });

  it("keeps manifests for the planner but out of the model's prompt, except the Android manifest", () => {
    expect(isModelContextFile("package.json")).toBe(false);
    expect(isModelContextFile("apps/api/go.mod")).toBe(false);
    expect(isModelContextFile("androidApp/src/main/AndroidManifest.xml")).toBe(true);
    expect(isModelContextFile("lib/router/index.js")).toBe(true);
    expect(isModelContextFile("tests/foo.go")).toBe(false);
  });
});
