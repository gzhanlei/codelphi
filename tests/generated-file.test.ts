import { describe, expect, it } from "vitest";
import { generatedFileMarker } from "../lib/slice-planner/generated-file";

const lines = (...text: string[]) => text;

describe("recognising a generated file by its header", () => {
  it("knows the headers the code generators of different stacks write", () => {
    // Go：sqlc、protoc、wire、gRPC
    expect(generatedFileMarker(lines("// Code generated by sqlc. DO NOT EDIT.", "", "package db"))).toBe("sqlc");
    expect(generatedFileMarker(lines("// Code generated by protoc-gen-go. DO NOT EDIT.", "// source: user.proto"))).toBe("protoc-gen-go");
    expect(generatedFileMarker(lines("// Code generated by wiregen.go; DO NOT EDIT."))).toBe("wiregen.go");
    // Flutter（Android、iOS、macOS、Linux、Windows 各一份）
    expect(generatedFileMarker(lines("//  Generated file. Do not edit.", "import Flutter"))).toBe("generated file");
    // OpenAPI 的 TypeScript 生成器、Python 的 protobuf
    expect(generatedFileMarker(lines("/* generated by openapi-typescript-codegen -- do not edit */"))).toBe("openapi-typescript-codegen");
    expect(generatedFileMarker(lines("# Generated by the protocol buffer compiler.  DO NOT EDIT!", "", "import proto"))).toBe("generated file");
    // @generated：protoc、tsdoc、Terraform 文档生成器的惯例
    expect(generatedFileMarker(lines("// @generated by protoc-gen-go. DO NOT EDIT."))).toBe("@generated");
    expect(generatedFileMarker(lines("/**", " * @generated", " */", "export const x = 1;"))).toBe("@generated");
    expect(generatedFileMarker(lines("/* eslint-disable */", "// @generated", "export const x = 1;"))).toBe("@generated");
    // 块注释里的星号行、HTML 注释、SQL 的 -- 注释
    expect(generatedFileMarker(lines("/**", " * GENERATED FILE — do not edit by hand.", " */"))).toBe("generated file");
    expect(generatedFileMarker(lines("<!-- Generated by Sphinx. Do not edit. -->"))).toBe("Sphinx");
    expect(generatedFileMarker(lines("-- Generated by pgproto3. DO NOT EDIT."))).toBe("pgproto3");
    // 版本号留在名字里
    expect(generatedFileMarker(lines("// Code generated by protoc-gen-go-v3.21.9. DO NOT EDIT."))).toBe("protoc-gen-go-v3.21.9");
  });

  it("keeps product code that only talks about generating", () => {
    // 审计（2026-11-27）里的真实误伤：只说了「生成」，没说「不要手改」。
    expect(generatedFileMarker(lines("// Codes are generated with a cryptographically secure RNG and stored in Redis.", "package otp"))).toBeNull();
    expect(generatedFileMarker(lines("/**", " * Authentication: JWT Bearer token generated from Access Key + Secret Key.", " */"))).toBeNull();
    expect(generatedFileMarker(lines("/**", " * Font families. fonts.css is GENERATED from this file by the build.", " */"))).toBeNull();
    // 现在很多手写代码的文件头带着 AI 署名。
    expect(generatedFileMarker(lines("// Generated with Claude Code", "// SPDX-License-Identifier: MIT", "export const x = 1;"))).toBeNull();
    expect(generatedFileMarker(lines("// Co-Authored-By: Claude <noreply@anthropic.com>", "package main"))).toBeNull();
    // 「不要手改」说的是别的（一个区块、一个配置值），不是整个文件是生成的。
    expect(generatedFileMarker(lines("// Do not edit the line below; it is checked by the release script.", "export const version = \"1.0.0\";"))).toBeNull();
  });

  it("only looks at comment lines at the top of the file", () => {
    // 第 16 行才出现：不算文件头。
    expect(generatedFileMarker([...Array.from({ length: 15 }, () => "code;"), "// Code generated by x. DO NOT EDIT."])).toBeNull();
    // 不是注释：装饰器、字符串里的字样。
    expect(generatedFileMarker(["@generated()", "export const x = 1;"])).toBeNull();
    expect(generatedFileMarker(['export const note = "// @generated";'])).toBeNull();
    // shebang 不妨碍下一行的标记。
    expect(generatedFileMarker(lines("#!/usr/bin/env python3", "# Code generated by x. DO NOT EDIT."))).toBe("x");
    // 空文件、什么都不说。
    expect(generatedFileMarker([])).toBeNull();
  });
});
